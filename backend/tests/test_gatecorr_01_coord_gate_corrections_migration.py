_PG_SKIP = pytest.mark.skipif(
    not can_connect(admin_database_url()),
    reason=(
        "Postgres not reachable at the conftest URL. CI provisions a postgres "
        "service; locally, set QONTINUI_TEST_PG=localhost:<port>."
    ),
)


def _columns(engine: Engine) -> dict[str, tuple[str, str]]:
    with engine.connect() as conn:
        return {
            r.column_name: (r.data_type, r.is_nullable)
            for r in conn.execute(
                text(
                    "SELECT column_name, data_type, is_nullable "
                    "FROM information_schema.columns "
                    "WHERE table_schema = :schema AND table_name = :table"
                ),
                {"schema": _SCHEMA, "table": _TABLE},
            )
        }


def _foreign_keys(engine: Engine) -> set[str]:
    with engine.connect() as conn:
        return {
            r[0]
            for r in conn.execute(
                text(
                    "SELECT conname FROM pg_constraint "
                    "WHERE conrelid = 'coord.gate_corrections'::regclass "
                    "AND contype = 'f'"
                )
            )
        }


def _insert(engine: Engine, **overrides: object) -> uuid.UUID:
    """Insert one correction the way coord's verb will, and return its id."""
    row = {
        "gate_id": uuid.uuid4(),
        "tenant_id": _TENANT,
        "relation": "mispredicated",
        "reason": "predicate asked migration_at_head; the table is absent",
        "replacement_gate_id": None,
        "corrected_by_device_id": None,
        "corrected_by_agent_id": None,
    }
    row.update(overrides)
    with engine.begin() as conn:
        return conn.execute(  # type: ignore[return-value]
            text(
                "INSERT INTO coord.gate_corrections "
                "(gate_id, tenant_id, relation, reason, replacement_gate_id, "
                " corrected_by_device_id, corrected_by_agent_id) "
                "VALUES (:gate_id, :tenant_id, :relation, :reason, "
                "        :replacement_gate_id, :corrected_by_device_id, "
                "        :corrected_by_agent_id) "
                "RETURNING correction_id"
            ),
            row,
        ).scalar_one()


@_PG_SKIP
def test_upgrade_write_downgrade_upgrade_round_trip() -> None:
    root = backend_root()
    with ephemeral_database(admin_database_url(), "gatecorr") as (engine, db_url):
        # The chain up to, but not including, this revision.
        run_alembic(root, db_url, "upgrade", _PARENT_REVISION_ID)
        assert not table_exists(engine, _SCHEMA, _TABLE), (
            "the parent must not already carry this table"
        )

        run_alembic(root, db_url, "upgrade", "head")
        assert table_exists(engine, _SCHEMA, _TABLE)
        assert index_exists(engine, _INDEX, schema=_SCHEMA)

        columns = _columns(engine)
        assert columns == _EXPECTED_COLUMNS, (
            "column shape drifted from what coord's correction verb inserts"
        )

        assert _foreign_keys(engine) == set(), (
            "gate_id is deliberately FK-free: an annotation about a gate must "
            "not couple its lifetime to coord.gates"
        )

        # The default mints the id, so coord inserts without one.
        first = _insert(engine)
        assert isinstance(first, uuid.UUID)

        # N corrections per gate — no unique constraint stands in the way of a
        # correction being itself corrected.
        gate = uuid.uuid4()
        replacement = uuid.uuid4()
        _insert(engine, gate_id=gate, relation="reopened_from")
        _insert(
            engine,
            gate_id=gate,
            relation="repointed_from",
            replacement_gate_id=replacement,
            corrected_by_device_id=uuid.uuid4(),
            corrected_by_agent_id=uuid.uuid4(),
        )
        with engine.connect() as conn:
            count = conn.execute(
                text(
                    "SELECT count(*) FROM coord.gate_corrections "
                    "WHERE tenant_id = :t AND gate_id = :g"
                ),
                {"t": _TENANT, "g": gate},
            ).scalar_one()
        assert count == 2

        # created_at is filled by the insert clock, not by the caller.
        with engine.connect() as conn:
            created = conn.execute(
                text(
                    "SELECT created_at FROM coord.gate_corrections "
                    "WHERE correction_id = :id"
                ),
                {"id": first},
            ).scalar_one()
        assert created is not None

        # head -> parent -> head leaves no residue and re-creates cleanly.
        run_alembic(root, db_url, "downgrade", "-1")
        assert not table_exists(engine, _SCHEMA, _TABLE)
        assert not index_exists(engine, _INDEX, schema=_SCHEMA)

        run_alembic(root, db_url, "upgrade", "head")
        assert table_exists(engine, _SCHEMA, _TABLE)
        assert index_exists(engine, _INDEX, schema=_SCHEMA)


@_PG_SKIP
@pytest.mark.parametrize("relation", _RELATIONS)
def test_the_check_admits_every_word_in_the_vocabulary(relation: str) -> None:
    root = backend_root()
    with ephemeral_database(admin_database_url(), "gatecorr_ok") as (engine, db_url):
        run_alembic(root, db_url, "upgrade", "head")
        assert _insert(engine, relation=relation) is not None


@_PG_SKIP
def test_the_check_refuses_a_word_outside_the_vocabulary() -> None:
    """A typo in a writer must be an IntegrityError here, not a word the
    console silently paints."""
    root = backend_root()
    with ephemeral_database(admin_database_url(), "gatecorr_bad") as (engine, db_url):
        run_alembic(root, db_url, "upgrade", "head")
        with pytest.raises(IntegrityError):
            _insert(engine, relation="superseded_by")

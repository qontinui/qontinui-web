"""The plan-library keyset walk and the shared cursor codec behind it.

Plan ``2026-09-05-every-bounded-read-is-a-page-that-reads-as-a-corpus``
Phase 4. Four guarantees, each pinned here:

1. **The Python codec IS the Rust codec.** ``app.core.bounded_read`` decodes
   tokens Rust ``page.rs`` minted (a committed fixture, never regenerated by
   Python) and re-mints them byte for byte — the cross-language guard Phase 1
   deferred to the codec's first consumer.
2. **A bad cursor is a typed 400** ``cursor_malformed`` naming ``cursor`` —
   garbage, a padded token, a token replayed under different filters — never a
   500 and never a silently different page.
3. **D8: the sort key is immutable.** Every walk keys on ``created_at``; a grep
   over ``app/`` and the migrations proves nothing UPDATEs it. A walk keeps
   every row even when an unreached row is UPDATED mid-walk — which the old
   ``updated_at DESC`` + ``OFFSET`` order could not.
4. **No silent truncation.** ``/candidates`` discloses a capped coord walk on
   the wire (``work_unit_population_state: "truncated"``, a non-exact bound),
   and a ``?q=`` search page carries ``total`` / ``truncated`` / a cursor.
"""


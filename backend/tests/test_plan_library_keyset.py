#: Fixture scope ``type`` → the Python builder method (Rust's ``bool`` is
#: ``boolean`` here, so it does not shadow the builtin inside the class).
_SCOPE_METHODS = {
    "opt_str": "opt_str",
    "uuid": "uuid",
    "opt_uuid": "opt_uuid",
    "bool": "boolean",
    "i64": "i64",
    "str_set": "str_set",
}


def _fixture_cases() -> list[dict[str, Any]]:
    return list(json.loads(FIXTURE.read_text(encoding="utf-8"))["cases"])


def _fingerprint(case: dict[str, Any]) -> br.ScopeFingerprint:
    scope = br.CursorScope(br.SortKey(case["sort_key"]))
    for field in case["scope"]:
        value = field["value"]
        if field["type"] in ("uuid", "opt_uuid") and value is not None:
            value = UUID(value)
        getattr(scope, _SCOPE_METHODS[field["type"]])(field["name"], value)
    return scope.finish()


def _b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")



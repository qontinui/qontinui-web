#: An UPDATE of either walked table whose SET clause names ``created_at``.
_SQL_UPDATE = re.compile(
    r"UPDATE\s+(?:agent\.)?work_artifact(?:s|_edges)\b[^;]{0,600}?"
    r"\bSET\b[^;]{0,600}?\bcreated_at\b",
    re.IGNORECASE | re.DOTALL,
)
#: A SQLAlchemy ``update(WorkArtifact…)`` whose values name ``created_at``.
_ORM_UPDATE = re.compile(
    r"update\(\s*WorkArtifact(?:Edge)?\s*\)[^#]{0,600}?\bcreated_at\s*[=:]",
    re.DOTALL,
)
#: An attribute write / metadata tuple naming the column.
_ATTR_WRITE = re.compile(r"\.created_at\s*=(?!=)|\(\s*\"created_at\"\s*,")


def _sources() -> list[Path]:
    return [
        *sorted((BACKEND / "app").rglob("*.py")),
        *sorted((BACKEND / "alembic" / "versions").glob("*.py")),
    ]


class TestTheSortKeyIsImmutable:
    def test_the_patterns_catch_what_they_claim_to(self) -> None:
        """Self-validation: a grep that matches nothing proves nothing."""
        assert _SQL_UPDATE.search(
            "UPDATE agent.work_artifacts SET status = 'x', created_at = now()"
        )
        assert _SQL_UPDATE.search("update work_artifact_edges\n set created_at=now()")
        assert _ORM_UPDATE.search("update(WorkArtifact).values(created_at=now)")
        assert _ATTR_WRITE.search("row.created_at = moment")
        assert _ATTR_WRITE.search('("created_at", metadata.created_at)')
        assert not _SQL_UPDATE.search("UPDATE agent.work_artifacts SET status = 'x'")

    def test_nothing_updates_a_walked_created_at(self) -> None:
        hits: list[str] = []
        for path in _sources():
            text = path.read_text(encoding="utf-8")
            rel = path.relative_to(BACKEND).as_posix()
            for pattern in (_SQL_UPDATE, _ORM_UPDATE):
                hits.extend(
                    f"{rel}: {m.group(0)[:80]!r}" for m in pattern.finditer(text)
                )
            if "WorkArtifact" in text:
                hits.extend(
                    f"{rel}: {m.group(0)!r}" for m in _ATTR_WRITE.finditer(text)
                )
        assert not hits, (
            "a keyset sort key (agent.work_artifacts / work_artifact_edges "
            "created_at) gained an UPDATE site — an unreached row whose key "
            "moves across a cursor is silently dropped from the walk (D8):\n"
            + "\n".join(hits)
        )

    def test_authored_at_is_written_which_is_why_it_never_keys_a_walk(self) -> None:
        """D8 names ``authored_at`` as eligible; here it is NOT — the upsert
        rewrites it. If this ever stops matching, it may become eligible."""
        crud_src = (BACKEND / "app" / "crud" / "work_artifact.py").read_text(
            encoding="utf-8"
        )
        assert re.search(r"\(\s*\"authored_at\"\s*,", crud_src)
        for key in (
            crud.ARTIFACT_LIST_SORT_KEY,
            crud.CANDIDATE_SORT_KEY,
            crud.FOLLOWUP_SORT_KEY,
        ):
            assert "authored_at" not in key.id and "updated_at" not in key.id



async def _post(client: httpx.AsyncClient, **overrides: Any) -> dict[str, Any]:
    resp = await client.post(API_PREFIX, json=_payload(**overrides))
    assert resp.status_code in (200, 201), resp.text
    return dict(resp.json()["artifact"])


async def _walk(
    client: httpx.AsyncClient, path: str, params: dict[str, Any]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Every page of a walk, following ``next_cursor`` to its end."""
    rows: list[dict[str, Any]] = []
    pages: list[dict[str, Any]] = []
    cursor: str | None = None
    for _ in range(50):
        query = dict(params)
        if cursor is not None:
            query["cursor"] = cursor
        resp = await client.get(path, params=query)
        assert resp.status_code == 200, resp.text
        page = resp.json()
        pages.append(page)
        rows.extend(page["items"])
        cursor = page["next_cursor"]
        if cursor is None:
            return rows, pages
    raise AssertionError("the walk did not terminate")


@pytest.mark.asyncio
class TestTheListWalk:
    async def test_the_walk_tiles_the_corpus_and_every_page_states_its_bound(
        self, client: httpx.AsyncClient
    ) -> None:
        stem = f"walk-{uuid4().hex[:8]}"
        ids = {
            (await _post(client, slug=f"{stem}-{n}", work_unit_slug=stem))["id"]
            for n in range(5)
        }
        rows, pages = await _walk(
            client, API_PREFIX, {"work_unit_slug": stem, "limit": 2}
        )
        assert [r["id"] for r in rows] == list(dict.fromkeys(r["id"] for r in rows))
        assert {r["id"] for r in rows} == ids
        assert [p["total"] for p in pages] == [5, 3, 1]
        assert [p["truncated"] for p in pages] == [True, True, False]
        assert all(p["bound_kind"] == "exact" for p in pages)
        assert all(p["enumerate_via"] is None for p in pages)
        assert pages[0]["ordering"] == "newest_captured_first"
        assert "offset" not in pages[0]

    async def test_an_update_mid_walk_does_not_drop_the_row(
        self, client: httpx.AsyncClient
    ) -> None:
        """The defect D8 exists for: under ``updated_at DESC`` an unreached row
        that is written to jumps ahead of the cursor and is never served."""
        stem = f"mutate-{uuid4().hex[:8]}"
        posted = [
            await _post(client, slug=f"{stem}-{n}", work_unit_slug=stem, body=f"v{n}")
            for n in range(4)
        ]
        first = await client.get(
            API_PREFIX, params={"work_unit_slug": stem, "limit": 2}
        )
        page1 = first.json()
        seen = {r["id"] for r in page1["items"]}
        unreached = next(p for p in posted if p["id"] not in seen)
        await _post(
            client,
            slug=unreached["slug"],
            work_unit_slug=stem,
            body="rewritten mid-walk",
            status="SHIPPED",
        )
        rest, _ = await _walk(
            client,
            API_PREFIX,
            {"work_unit_slug": stem, "limit": 2, "cursor": page1["next_cursor"]},
        )
        assert seen | {r["id"] for r in rest} == {p["id"] for p in posted}

    async def test_a_cursor_replayed_under_other_filters_is_a_typed_400(
        self, client: httpx.AsyncClient
    ) -> None:
        stem = f"replay-{uuid4().hex[:8]}"
        for n in range(3):
            await _post(client, slug=f"{stem}-{n}", work_unit_slug=stem)
        page = (
            await client.get(API_PREFIX, params={"work_unit_slug": stem, "limit": 1})
        ).json()
        replayed = await client.get(
            API_PREFIX, params={"kind": "plan", "cursor": page["next_cursor"]}
        )
        assert replayed.status_code == 400, replayed.text
        detail = replayed.json()["detail"]
        assert detail["error"] == "cursor_malformed"
        assert detail["parameter"] == "cursor"
        assert detail["reason"] == "scope"

        garbage = await client.get(API_PREFIX, params={"cursor": "%%%"})
        assert garbage.status_code == 400
        assert garbage.json()["detail"]["error"] == "cursor_malformed"

    async def test_offset_is_deleted_not_deprecated(
        self, client: httpx.AsyncClient
    ) -> None:
        for path in ("", "/candidates", "/followups", "/reconciliation"):
            resp = await client.get(f"{API_PREFIX}{path}", params={"offset": 0})
            assert resp.status_code == 422, (path, resp.text)
            assert "unknown_query_parameter" in resp.text, path

    async def test_a_search_page_discloses_its_bound_and_walks_on(
        self, client: httpx.AsyncClient
    ) -> None:
        """``?q=`` returned exactly one page with no count and no way on; a
        capped search page is not evidence that a plan is absent."""
        word = f"zebrafinch{uuid4().hex[:6]}"
        ids = {
            (await _post(client, slug=f"q-{word}-{n}", body=f"# about {word}"))["id"]
            for n in range(3)
        }
        rows, pages = await _walk(client, API_PREFIX, {"q": word, "limit": 2})
        assert pages[0]["total"] == 3
        assert pages[0]["truncated"] is True
        assert pages[0]["next_cursor"]
        assert {r["id"] for r in rows} == ids


@pytest.mark.asyncio
class TestCandidatesNeverTruncateSilently:
    async def test_a_capped_coord_walk_is_disclosed_on_the_wire(
        self, client: httpx.AsyncClient
    ) -> None:
        """coord serves a full page forever; the walk stops at its cap. The
        response must SAY so — a log line is not a disclosure."""

        async def _endless(path: str, **kwargs: Any) -> Any:
            if path in ("/coord/work-units", "/coord/agent-work-units"):
                offset = int((kwargs.get("params") or {}).get("offset", "0"))
                unit = _coord_unit(
                    f"2026-07-0{offset + 1}-endless-{offset}",
                    created_at=f"2026-07-0{offset + 1}T00:00:00Z",
                )
                return {"work_units": [unit], "limit": 1, "offset": offset}
            return {}

        with (
            patch("app.api.v1.endpoints.plan_library._COORD_UNIT_PAGE_LIMIT", 1),
            patch("app.api.v1.endpoints.plan_library._COORD_UNIT_MAX_PAGES", 2),
            patch(
                "app.api.v1.endpoints.plan_library._proxy_coord_get",
                new=AsyncMock(side_effect=_endless),
            ),
            patch(
                "app.api.v1.endpoints.plan_library._soft_tenant_id",
                new=AsyncMock(return_value=uuid4()),
            ),
        ):
            # include_coord stays on; the walk is followed to its end. The
            # NULL org bucket may hold other tests' committed plans, so the
            # page count is not fixed — the bound on each page is.
            pages = []
            cursor: str | None = None
            for _ in range(500):
                params: dict[str, Any] = {"limit": 1}
                if cursor is not None:
                    params["cursor"] = cursor
                resp = await client.get(f"{API_PREFIX}/candidates", params=params)
                assert resp.status_code == 200, resp.text
                pages.append(resp.json())
                cursor = pages[-1]["next_cursor"]
                if cursor is None:
                    break

        assert len(pages) >= 2
        assert all(p["work_unit_population_state"] == "truncated" for p in pages)
        assert all(p["work_unit_population_reason"] for p in pages)
        assert all(p["total"] is None for p in pages), "never an exact count"
        for page in pages[:-1]:
            assert page["bound_kind"] == "at_least"
            assert page["truncated"] is True
            assert page["next_cursor"]
        # The last page shows everything READ, and nothing proves that was
        # everything: unknown, never a confident "that is all".
        assert pages[-1]["bound_kind"] == "unknown"
        assert pages[-1]["truncated"] is None
        slugs = [i["slug"] for p in pages for i in p["items"]]
        assert "2026-07-01-endless-0" in slugs and "2026-07-02-endless-1" in slugs

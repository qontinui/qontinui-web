_KEY = br.SortKey("test.rows:created_at,id")


def _fp(tenant: str = "a") -> br.ScopeFingerprint:
    return br.CursorScope(_KEY).opt_str("tenant", tenant).finish()


def _payload_token(fp: br.ScopeFingerprint, **override: Any) -> str:
    body: dict[str, Any] = {
        "v": 1,
        "s": fp.sort_key.id,
        "k": 1_700_000_000_000_000,
        "i": str(uuid4()),
        "f": fp.hex,
    }
    body.update(override)
    return _b64(json.dumps(body, separators=(",", ":")).encode())


class TestStrictDecode:
    def test_round_trip_at_microsecond_resolution(self) -> None:
        pos = br.KeysetPosition(
            at=datetime(2026, 9, 5, 1, 2, 3, 456789, tzinfo=UTC), id=uuid4()
        )
        assert _fp().decode(_fp().encode(pos)) == pos

    @pytest.mark.parametrize(
        ("token", "reason"),
        [
            ("", br.CursorRejection.EMPTY),
            ("   ", br.CursorRejection.EMPTY),
            ("A" * (br.CURSOR_MAX_TOKEN_LEN + 1), br.CursorRejection.TOO_LONG),
            ("not base64!", br.CursorRejection.ENCODING),
            ("abc+/", br.CursorRejection.ENCODING),
            ("A", br.CursorRejection.ENCODING),
            (_b64(b"not json"), br.CursorRejection.PAYLOAD),
            (_b64(b"[1,2]"), br.CursorRejection.PAYLOAD),
        ],
    )
    def test_garbage_is_a_cursor_error_never_a_crash(
        self, token: str, reason: br.CursorRejection
    ) -> None:
        with pytest.raises(br.CursorError) as exc:
            _fp().decode(token)
        assert exc.value.reason is reason

    def test_a_padded_token_is_refused(self) -> None:
        token = _fp().encode(br.KeysetPosition(at=datetime.now(UTC), id=uuid4()))
        padded = token + "=" * (-len(token) % 4 or 4)
        with pytest.raises(br.CursorError) as exc:
            _fp().decode(padded)
        assert exc.value.reason is br.CursorRejection.ENCODING

    def test_non_canonical_trailing_bits_are_refused(self) -> None:
        """The Rust engine refuses them; so must the twin."""
        token = _fp().encode(br.KeysetPosition(at=datetime.now(UTC), id=uuid4()))
        if len(token) % 4 == 0:  # pragma: no cover — no spare bits to flip
            pytest.skip("this token length carries no trailing bits")
        alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
        last = alphabet.index(token[-1])
        tweaked = token[:-1] + alphabet[last ^ 1]
        with pytest.raises(br.CursorError) as exc:
            _fp().decode(tweaked)
        assert exc.value.reason in (
            br.CursorRejection.ENCODING,
            br.CursorRejection.PAYLOAD,
        )

    @pytest.mark.parametrize(
        "override",
        [
            {"x": 1},  # an unknown field
            {"k": 1.5},
            {"k": True},
            {"v": "1"},
            {"v": 256},
            {"i": "not-a-uuid"},
            {"k": 2**63},
        ],
    )
    def test_a_payload_rust_would_not_parse_is_refused(
        self, override: dict[str, Any]
    ) -> None:
        with pytest.raises(br.CursorError) as exc:
            _fp().decode(_payload_token(_fp(), **override))
        assert exc.value.reason is br.CursorRejection.PAYLOAD

    def test_a_duplicate_field_is_refused(self) -> None:
        fp = _fp()
        raw = (
            f'{{"v":1,"v":1,"s":"{fp.sort_key.id}","k":0,'
            f'"i":"{uuid4()}","f":"{fp.hex}"}}'
        ).encode()
        with pytest.raises(br.CursorError) as exc:
            fp.decode(_b64(raw))
        assert exc.value.reason is br.CursorRejection.PAYLOAD

    def test_version_sort_key_scope_and_range_each_refuse(self) -> None:
        fp = _fp()
        for override, reason in (
            ({"v": 2}, br.CursorRejection.VERSION),
            ({"s": "other:created_at,id"}, br.CursorRejection.SORT_KEY),
            ({"f": _fp("b").hex}, br.CursorRejection.SCOPE),
            ({"k": -(2**62)}, br.CursorRejection.TIMESTAMP),
        ):
            with pytest.raises(br.CursorError) as exc:
                fp.decode(_payload_token(fp, **override))
            assert exc.value.reason is reason, override

    def test_an_empty_cursor_param_is_the_first_page(self) -> None:
        """``?cursor=`` reads as no cursor (coord's grammar); ``decode`` itself
        stays strict about an empty token."""
        for token in (None, "", "   "):
            assert _fp().decode_param(token, surface="GET /x") is None

    def test_the_refusal_is_a_typed_400_naming_the_parameter(self) -> None:
        with pytest.raises(HTTPException) as exc:
            _fp().decode_param("garbage!", surface="GET /x")
        assert exc.value.status_code == 400
        detail = exc.value.detail
        assert isinstance(detail, dict)
        assert detail["error"] == "cursor_malformed"
        assert detail["parameter"] == "cursor"
        assert "GET /x" in detail["message"]
        assert "garbage" not in json.dumps(detail), "the token must not echo"

    def test_scope_fields_are_tagged_so_absence_never_collides(self) -> None:
        none = br.CursorScope(_KEY).opt_str("q", None).finish()
        empty = br.CursorScope(_KEY).opt_str("q", "").finish()
        literal_n = br.CursorScope(_KEY).opt_str("q", "n").finish()
        assert len({none.hex, empty.hex, literal_n.hex}) == 3

    def test_str_set_is_order_and_duplicate_insensitive(self) -> None:
        a = br.CursorScope(_KEY).str_set("r", ["b", "a", "a"]).finish()
        b = br.CursorScope(_KEY).str_set("r", ["a", "b"]).finish()
        assert a == b



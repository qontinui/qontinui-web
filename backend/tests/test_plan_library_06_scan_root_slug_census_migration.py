def test_down_revision_pins_the_head_it_was_authored_against() -> None:
    match = re.search(
        r'down_revision[^=]*=\s*\(?\s*["\'](?P<parent>[^"\']+)["\']',
        _revision_source(),
    )
    assert match is not None
    assert match.group("parent") == _PARENT_REVISION_ID


def test_the_revision_id_is_unique_in_the_chain() -> None:
    versions = backend_root() / "alembic" / "versions"
    same_id = [
        path.name
        for path in versions.glob("*.py")
        if re.search(
            rf'^revision[^=]*=\s*["\']{re.escape(_REVISION_ID)}["\']',
            path.read_text(encoding="utf-8"),
            re.MULTILINE,
        )
    ]
    assert same_id == [_REVISION_FILENAME], (
        f"revision id {_REVISION_ID!r} is claimed by {same_id}"
    )


def test_it_was_hand_authored_not_autogenerated() -> None:
    """``alembic revision --autogenerate`` is never run against this chain
    (served policy ``production-and-cost`` ``alembic-sole-authorship``); its
    output leaves these markers."""
    source = _revision_source()
    assert "### commands auto generated by Alembic" not in source



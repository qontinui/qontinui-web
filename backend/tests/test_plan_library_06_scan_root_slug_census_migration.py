"""Round-trip + upsert test for ``plan_library_06_scan_root_slug_census``.

Phase 1 (web half) of
``2026-09-15-captured-vs-authored-coverage-is-a-set-difference``.

The API suite runs against a ``create_all`` schema built from the MODEL, so it
cannot notice a migration that disagrees with it. What would bite only in
production here is the census resolution: the upsert compares an incoming
digest with the STORED one and calls ``jsonb_set`` on the stored census, so a
column that is TEXT rather than JSONB, or missing altogether, is an error on the
first device to report a census and nowhere else. The walk below therefore runs
the crud's EXACT statement (:func:`app.crud.plan_scan_root.upsert_statement`)
against the alembic-built table, through both directions of the withheld-set
rule.

Also asserted: the six columns land nullable and with the right types, that an
absent census stores **SQL NULL rather than the JSONB scalar ``null``** on all
three write paths (the no-census INSERT, the source-omitted UPDATE and the
idle-cycle UPDATE) — a distinction no Python-side assertion in this suite can
see, because JSONB ``null`` deserializes to ``None`` — the table's constraints
are UNCHANGED (this revision adds none), and head → downgrade → head leaves no
residue.

Substrate is ``tests/_alembic_harness``. ⚠️ A skip proves nothing — point it at
a live instance with ``QONTINUI_TEST_PG=localhost:<port>`` when 5432 is not the
one accepting the test credentials.
"""

